import '../domain/ai_models.dart';

/// The shape of output a request expects. Adapters translate this into their
/// own structured-output configuration (e.g. a Gemini response schema).
enum AiOutputFormat { text, diagnostic, advice, goals, summary, studyPlan }

class AiTurn {
  const AiTurn(this.role, this.text);
  final ChatRole role;
  final String text;
}

class AiRequest {
  const AiRequest({
    required this.format,
    required this.prompt,
    this.history = const <AiTurn>[],
    this.maxOutputTokens = 1024,
    this.timeout,
  });

  final AiOutputFormat format;

  /// The final user message (data context included by the caller).
  final String prompt;

  /// Earlier turns (chat only), oldest first, already trimmed.
  final List<AiTurn> history;
  final int maxOutputTokens;
  final Duration? timeout;
}

/// A text-generation backend. The app uses the direct Gemini Developer API; tests use a
/// fake. Implementations throw `AiFailure` for every error.
abstract class AiProvider {
  /// Shown in the UI ("Generated by …") and stored with results.
  String get modelName;

  /// The system instruction for [format] is owned by the provider
  /// configuration (see `AiPrompts.systemFor`).
  Future<String> generate(AiRequest request);
}
