late FakeInsightsProvider _insights;
late FakeAiProvider _ai;
late InMemoryAiStore _store;
late List<String> _applied;

AiAssistantController _controller() => AiAssistantController(
  insights: _insights,
  provider: _ai,
  store: _store,
  currentUserId: () => 'alice',
  limiter: AiUsageLimiter(minInterval: Duration.zero, clock: () => bNow),
  clock: () => bNow,
  loadPreferences: (_) async =>
      const StudyPreferences(preferredStudyTime: 'Evening'),
  applyGoal: (u, g, h) async => _applied.add('${g.name}:$h'),
  behaviorInsights: () => const <Recommendation>[
    Recommendation(
      id: 'r',
      title: 'Rule-based tip from your data',
      action: 'Put the phone away for your next study block.',
      evidence: 'App use today: 5h 00m.',
      priority: 1,
    ),
  ],
);

Widget _app(Widget home, {ThemeMode mode = ThemeMode.light}) => MaterialApp(
  theme: AppTheme.lightTheme,
  darkTheme: AppTheme.darkTheme,
  themeMode: mode,
  home: home,
);

String _longText(int words) => List<String>.generate(
  words,
  (i) => i % 9 == 0 ? 'Recorded:' : 'productivity',
).join(' ');

void main() {
  setUp(() {
    SharedPreferences.setMockInitialValues(<String, Object>{});
    GoogleFonts.config.allowRuntimeFetching = false;
    _insights = FakeInsightsProvider(richHistory());
    _ai = FakeAiProvider();
    _store = InMemoryAiStore();
    _applied = <String>[];
  });

  Future<void> pumpTall(
    WidgetTester tester,
    Widget w, {
    ThemeMode mode = ThemeMode.light,
  }) async {
    tester.view.physicalSize = const Size(800, 10000);
    tester.view.devicePixelRatio = 2;
    addTearDown(tester.view.reset);
    await tester.pumpWidget(_app(w, mode: mode));
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 100));
  }

  group('AI Assistant screen', () {
    testWidgets('debug diagnostic sends only an explicit minimal probe', (
      tester,
    ) async {
      _ai.responses.add('VIVORA_OK');
      final c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.tap(find.byTooltip('AI diagnostics'));
      await tester.pumpAndSettle();
      expect(_ai.requests, isEmpty);
      await tester.tap(find.text('Test connection'));
      await tester.pumpAndSettle();
      expect(find.textContaining('Success: model responded'), findsOneWidget);
      expect(_ai.requests, hasLength(1));
      expect(_store.chats, isEmpty);
    });
    testWidgets('empty state → generate → recommendation cards with feedback', (
      tester,
    ) async {
      _ai.responses.add(adviceJson());
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));

      expect(find.text('Personal Digital Twin AI'), findsOneWidget);
      expect(find.text('Ask Personal Digital Twin AI'), findsOneWidget);
      expect(find.text('Generate recommendations'), findsOneWidget);
      // Rule-based insights are shown (and labelled) before any AI output.
      expect(find.text('Behaviour insights'), findsOneWidget);
      expect(
        find.text('Rule-based from your data, not generated by AI'),
        findsOneWidget,
      );
      expect(
        _ai.requests,
        isEmpty,
        reason: 'opening the screen does not call the AI',
      );

      await tester.tap(find.text('Generate recommendations'));
      await tester.pump();
      await tester.pump();
      expect(find.text('Add one more focus block'), findsOneWidget);
      expect(find.text('AI-generated'), findsWidgets);
      expect(find.text('High priority'), findsOneWidget);
      expect(
        find.textContaining('Based on: Deep focus (logged)'),
        findsOneWidget,
      );
      expect(find.text('Behaviour insights'), findsNothing);

      await tester.tap(find.text('Dismiss').first);
      await tester.pump();
      expect(
        find.widgetWithText(AiRecommendationCard, 'Add one more focus block'),
        findsNothing,
      );
      expect(
        find.textContaining('It will not be suggested again'),
        findsOneWidget,
      );
      expect(_store.statusUpdates.single, endsWith(':dismissed'));
      expect(find.text('Recent advice'), findsOneWidget);
    });

    testWidgets('loading state while the AI is working', (tester) async {
      _ai.gate = Completer<void>();
      _ai.responses.add(adviceJson());
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.tap(find.text('Generate recommendations'));
      await tester.pump();
      expect(
        find.text('Personal Digital Twin AI is reading your recorded data…'),
        findsOneWidget,
      );
      expect(find.byType(LinearProgressIndicator), findsOneWidget);
      _ai.gate!.complete();
      await tester.pump();
      await tester.pump();
      expect(find.byType(LinearProgressIndicator), findsNothing);
    });

    testWidgets('error state: friendly message, retry, fallback insights', (
      tester,
    ) async {
      _ai.responses.addAll(<Object>[
        const AiFailure(AiFailureKind.offline, 'SocketException: details'),
        adviceJson(),
      ]);
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.tap(find.text('Generate recommendations'));
      await tester.pump();
      await tester.pump();
      expect(
        find.text(const AiFailure(AiFailureKind.offline).message),
        findsOneWidget,
      );
      expect(find.textContaining('SocketException'), findsNothing);
      expect(find.text('Rule-based tip from your data'), findsOneWidget);
      await tester.tap(find.text('Retry'));
      await tester.pump();
      await tester.pump();
      expect(find.text('Add one more focus block'), findsOneWidget);
    });

    testWidgets('not configured: no retry button offered', (tester) async {
      _ai.responses.add(const AiFailure(AiFailureKind.notConfigured));
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.tap(find.text('Generate recommendations'));
      await tester.pump();
      await tester.pump();
      expect(find.textContaining('not configured'), findsOneWidget);
      expect(find.text('Retry'), findsNothing);
    });

    testWidgets('goal suggestion requires confirmation before saving', (
      tester,
    ) async {
      _ai.responses.add(
        adviceJson(
          goals: <Map<String, Object?>>[
            <String, Object?>{
              'goal': 'focus',
              'suggestedHours': 2.5,
              'reason': 'A gradual step up.',
            },
          ],
        ),
      );
      final AiAssistantController c = _controller();
      await c.generateAdvice();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      expect(find.text('Suggested goals'), findsOneWidget);
      expect(find.textContaining('Current: 2h 00m'), findsOneWidget);
      await tester.tap(find.text('Apply goal'));
      await tester.pump();
      expect(find.text('Change your focus goal?'), findsOneWidget);
      await tester.tap(find.text('Cancel'));
      await tester.pump();
      expect(_applied, isEmpty);
      await tester.tap(find.text('Apply goal'));
      await tester.pump();
      await tester.tap(find.text('Apply'));
      await tester.pump();
      await tester.pump();
      expect(_applied, <String>['focus:2.5']);
      expect(find.text('Suggested goals'), findsNothing);
    });

    testWidgets('weekly service failure keeps explicitly local statistics', (
      tester,
    ) async {
      _ai.responses.add(const AiFailure(AiFailureKind.server));
      final c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.tap(find.text('Summaries'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Weekly'));
      await tester.pump();
      await tester.tap(find.text('Generate weekly summary'));
      await tester.pumpAndSettle();
      expect(c.summary(SummaryKind.weekly), isNull);
      expect(
        find.text('Local statistical weekly summary — not AI-generated'),
        findsOneWidget,
      );
      expect(
        find.textContaining('AI commentary is unavailable.'),
        findsOneWidget,
      );
      expect(find.text('2026-10-09 to 2026-10-15'), findsOneWidget);
      expect(find.text('62/100 (avg of 7 days)'), findsOneWidget);
      expect(find.text('AI-generated'), findsNothing);
    });

    testWidgets('summaries tab shows recorded facts separately from AI text', (
      tester,
    ) async {
      _ai.responses.add(summaryJson());
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.ensureVisible(find.text('Summaries'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Summaries'));
      await tester.pumpAndSettle();
      expect(find.text('Recorded (today)'), findsOneWidget);
      expect(
        find.text('Facts calculated by Personal Digital Twin, not by AI.'),
        findsOneWidget,
      );
      await tester.tap(find.text('Weekly'));
      await tester.pump();
      expect(
        find.text('Local statistical weekly summary — not AI-generated'),
        findsOneWidget,
      );
      await tester.tap(find.text('Generate weekly summary'));
      await tester.pump();
      await tester.pump();
      expect(find.text('A steady week'), findsOneWidget);
      expect(find.text('Next steps'), findsOneWidget);
      expect(find.text('Regenerate'), findsOneWidget);
    });

    testWidgets('study plan: suggestion only, goal change needs confirmation', (
      tester,
    ) async {
      _ai.responses.add(planJson());
      final AiAssistantController c = _controller();
      await c.open();
      await c.generateStudyPlan();
      await pumpTall(tester, AiAssistantScreen(controller: c));
      await tester.ensureVisible(find.text('Study plan'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Study plan'));
      await tester.pumpAndSettle();
      expect(find.textContaining('Suggestion only'), findsOneWidget);
      expect(find.text('2h 30m study per day'), findsOneWidget);
      expect(find.text('You prefer: Evening'), findsOneWidget);
      expect(find.textContaining('05:00'), findsNothing);
      expect(_store.plans['alice']!.acceptedAt, isNull);
      await tester.tap(find.text('Accept this plan'));
      await tester.pumpAndSettle();
      expect(find.text('Plan accepted'), findsOneWidget);
      expect(_store.plans['alice']!.acceptedAt, bNow);
      expect(_applied, isEmpty);
      await tester.tap(find.text('Use 2h 30m as study goal'));
      await tester.pump();
      await tester.tap(find.text('Update goal'));
      await tester.pump();
      await tester.pump();
      expect(_applied, <String>['study:2.5']);
    });

    testWidgets('dark mode uses dark surfaces', (tester) async {
      _ai.responses.add(adviceJson());
      final AiAssistantController c = _controller();
      await c.generateAdvice();
      await pumpTall(
        tester,
        AiAssistantScreen(controller: c),
        mode: ThemeMode.dark,
      );
      final BuildContext ctx = tester.element(
        find.text('Add one more focus block'),
      );
      expect(Theme.of(ctx).brightness, Brightness.dark);
      expect(ctx.palette.surface, VivoraPalette.dark.surface);
      final Text title = tester.widget<Text>(
        find.text('Add one more focus block'),
      );
      expect(
        title.style?.color ?? DefaultTextStyle.of(ctx).style.color,
        isNot(Colors.black),
      );
    });
  });

  group('Chat screen', () {
    testWidgets(
      'empty state with suggested questions; asking shows both bubbles',
      (tester) async {
        _ai.responses.add(
          'Recorded: you studied about 2 hours a day (last 7 days).',
        );
        final AiAssistantController c = _controller();
        await pumpTall(tester, AiChatScreen(controller: c));
        expect(find.text('Ask about your productivity'), findsOneWidget);
        expect(find.text('How productive was I this week?'), findsOneWidget);
        await tester.tap(find.text('How much time did I spend studying?'));
        await tester.pump();
        await tester.pump();
        await tester.pump(const Duration(milliseconds: 300));
        expect(
          find.text('How much time did I spend studying?'),
          findsOneWidget,
        );
        expect(
          find.textContaining('you studied about 2 hours'),
          findsOneWidget,
        );
        expect(find.byTooltip('Clear chat'), findsOneWidget);
      },
    );

    testWidgets('typing, sending, error and retry', (tester) async {
      _ai.responses.addAll(<Object>[
        const AiFailure(AiFailureKind.timeout),
        'Here is an answer.',
      ]);
      final AiAssistantController c = _controller();
      await pumpTall(tester, AiChatScreen(controller: c));
      await tester.enterText(find.byType(TextField), 'Why did my score drop?');
      await tester.pump();
      await tester.tap(find.byTooltip('Send'));
      await tester.pump();
      await tester.pump();
      expect(
        find.text(const AiFailure(AiFailureKind.timeout).message),
        findsOneWidget,
      );
      await tester.tap(find.text('Retry'));
      await tester.pump();
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 300));
      expect(find.text('Here is an answer.'), findsOneWidget);
      expect(find.text('Why did my score drop?'), findsOneWidget);
    });

    testWidgets('clear chat asks first', (tester) async {
      _store.chats['alice'] = <ChatMessage>[
        ChatMessage(id: 'a', role: ChatRole.user, text: 'Hi', createdAt: bNow),
      ];
      final AiAssistantController c = _controller();
      await c.open();
      await pumpTall(tester, AiChatScreen(controller: c));
      await tester.tap(find.byTooltip('Clear chat'));
      await tester.pump();
      expect(find.text('Clear chat history?'), findsOneWidget);
      await tester.tap(find.text('Clear'));
      await tester.pump();
      await tester.pump();
      expect(find.text('Ask about your productivity'), findsOneWidget);
      expect(_store.chats['alice'], isNull);
    });

    testWidgets('keyboard does not cover the input', (tester) async {
      final AiAssistantController c = _controller();
      tester.view.physicalSize = const Size(720, 1280);
      tester.view.devicePixelRatio = 2;
      tester.view.viewInsets = const FakeViewPadding(bottom: 300 * 2);
      addTearDown(tester.view.reset);
      await tester.pumpWidget(_app(AiChatScreen(controller: c)));
      await tester.pump();
      final Rect field = tester.getRect(find.byType(TextField));
      expect(field.bottom, lessThanOrEqualTo(640 - 300));
      expect(tester.takeException(), isNull);
    });
  });

  group('Reminders section', () {
    testWidgets('switch asks for permission and explains refusal', (
      tester,
    ) async {
      final FakeReminderPlatform platform = FakeReminderPlatform();
      final ReminderService service = ReminderService(
        platform: platform,
        clock: () => bNow,
      );
      await pumpTall(
        tester,
        Scaffold(
          body: ListView(
            children: <Widget>[RemindersSection(service: service)],
          ),
        ),
      );
      expect(find.text('REMINDERS'), findsOneWidget);
      await tester.tap(find.text('Daily log reminder'));
      await tester.pump();
      await tester.pump();
      expect(
        find.textContaining('Notifications are turned off'),
        findsOneWidget,
      );
      expect(service.settings.value.dailyLog, isFalse);

      platform.grantOnRequest = true;
      await tester.tap(find.text('Daily log reminder'));
      await tester.pump();
      await tester.pump();
      expect(service.settings.value.dailyLog, isTrue);
      expect(find.text('Log reminder time'), findsOneWidget);
    });
  });

  group('Responsive (7 widths × 6 font scales × 2 heights × light/dark)', () {
    testWidgets('assistant: recommendations and goal suggestions', (
      tester,
    ) async {
      _ai.responses.add(
        adviceJson(
          goals: <Map<String, Object?>>[
            <String, Object?>{
              'goal': 'screenLimit',
              'suggestedHours': 4,
              'reason': 'Reduce gradually from about 5 hours.',
            },
          ],
        ),
      );
      final AiAssistantController c = _controller();
      await tester.runAsync(c.generateAdvice);
      await expectResponsive(tester, () => AiAssistantScreen(controller: c));
    });

    testWidgets('assistant: empty and error states with fallback', (
      tester,
    ) async {
      _ai.responses.add(const AiFailure(AiFailureKind.quotaExceeded));
      final AiAssistantController c = _controller();
      await tester.runAsync(c.generateAdvice);
      await expectResponsive(tester, () => AiAssistantScreen(controller: c));
    });

    testWidgets('assistant: summaries and study plan tabs', (tester) async {
      _ai.responses.addAll(<Object>[summaryJson(), planJson()]);
      final AiAssistantController c = _controller();
      await tester.runAsync(() async {
        await c.open();
        await c.generateSummary(SummaryKind.daily);
        await c.generateStudyPlan();
      });
      for (final String tab in <String>['Summaries', 'Study plan']) {
        await expectResponsive(
          tester,
          () => AiAssistantScreen(controller: c),
          interact: (t) async {
            await t.ensureVisible(find.text(tab));
            await t.pumpAndSettle();
            await t.tap(find.text(tab));
            await t.pumpAndSettle();
          },
        );
      }
    });

    testWidgets('chat: long messages wrap without overflow', (tester) async {
      _store.chats['alice'] = <ChatMessage>[
        ChatMessage(
          id: 'u',
          role: ChatRole.user,
          text: _longText(60),
          createdAt: bNow,
        ),
        ChatMessage(
          id: 'a',
          role: ChatRole.assistant,
          text:
              '${_longText(250)}\n\nhttps://example.com/averyveryveryveryveryverylongunbrokenlinkwithoutanyspaces',
          createdAt: bNow,
        ),
      ];
      final AiAssistantController c = _controller();
      await tester.runAsync(c.open);
      await expectResponsive(tester, () => AiChatScreen(controller: c));
    });

    testWidgets('chat: empty state with suggestions', (tester) async {
      final AiAssistantController c = _controller();
      await expectResponsive(tester, () => AiChatScreen(controller: c));
    });
  });
}
